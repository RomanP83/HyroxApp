/**
 * One interval session for this athlete, this phase, this week.
 *
 * No session here names a station, so nothing is ever steered by a station
 * weakness: the rotation is a plain cycle through the phase's sessions, which
 * is what an unloaded running session should be.
 */
export function pickIntervalSession(q: IntervalQuery): IntervalPick | null {
  return pickFromCatalogue(INTERVAL_SESSIONS, q);
}

/** The session as lines to draw, round count included. */
export function renderInterval(session: IntervalSession): SessionLine[] {
  return renderCatalogue(session);
}
