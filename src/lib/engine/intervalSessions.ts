// ============================================================================
// Threshold and VO2max intervals, level by level and phase by phase.
//
// This is the one running session in the plan that carries no station work at
// all, and that is deliberate: a sled or a wall ball before the reps caps the
// speed and blurs the physiological target. Left alone, the session does what
// only it can — raise the ceiling of aerobic capacity and train lactate
// clearance at the paces the athlete could actually hold.
//
// What that means in metres and minutes is a different session at every level.
// A beginner runs three six-minute efforts at the bottom of the threshold; a
// sub-60 athlete runs eight kilometre reps at race pace off thirty seconds and
// is judged on a split variance of one to two seconds.
//
// Compromised running is the other half of the argument and lives next door;
// this catalogue never touches a station on purpose.
//
// Like the other catalogues, this file is the source of truth but not the
// store: every session is also a seeded workout_blocks row, generated by
// librarySeed.ts and keyed by the pinned block_id.
// ============================================================================

