// ============================================================================
// Isolated station work, level by level and phase by phase.
//
// A station session without running is not a lesser version of a race
// simulation. It buys movement economy, strength endurance and lactate
// tolerance at the machines while the legs and joints are spared the
// accumulated cost of the running — which is exactly why it can be prescribed
// in weeks where another hard run would be one too many.
//
// What that means in metres and kilos is not one prescription but twenty: a
// beginner learning to keep a low centre of gravity behind the sled and a
// sub-60 athlete pushing 50 m in under 1:15 are not doing the same session at
// a different weight.
//
// Race weights follow the rest of the engine: sled push 152 / 202 kg, sled
// pull 103 / 153 kg, farmers carry 2×24 / 2×32 kg, sandbag lunges 20 / 30 kg,
// wall balls 6 / 9 kg (open / pro). Overloads are written as what they are —
// a number above race weight — so the athlete can see the margin.
//
// Like compromised running, this file is the source of truth but not the
// store: every session is also a seeded workout_blocks row, generated by
// librarySeed.ts and keyed by the pinned block_id. Edit here, regenerate the
// seed, run it.
// ============================================================================

